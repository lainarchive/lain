#[derive(Debug, Clone, Deserialize, Serialize, ts_rs::TS)]
#[serde(tag = "command", rename_all = "snake_case", deny_unknown_fields)]
#[ts(tag = "command", rename_all = "snake_case")]
pub enum Intervention {
    Pause { session_id: String },
    Resume { session_id: String },
    Cancel { session_id: String },
    Steer { session_id: String, text: String },
    Intercept { session_id: String, enabled: bool },
    Approve { session_id: String, call_id: String },
    Deny { session_id: String, call_id: String },
}

impl Intervention {
    pub fn session_id(&self) -> &str {
        match self {
            Self::Pause { session_id }
            | Self::Resume { session_id }
            | Self::Cancel { session_id }
            | Self::Steer { session_id, .. }
            | Self::Intercept { session_id, .. }
            | Self::Approve { session_id, .. }
            | Self::Deny { session_id, .. } => session_id,
        }
    }
}

#[derive(Debug, Default)]
struct Journal {
    sequence: u64,
    history: VecDeque<EventEnvelope>,
    sessions: BTreeMap<String, SessionSnapshot>,
}

#[derive(Debug)]
pub struct DashboardHub {
    journal: Mutex<Journal>,
    sender: broadcast::Sender<EventEnvelope>,
}

impl Default for DashboardHub {
    fn default() -> Self {
        Self {
            journal: Mutex::default(),
            sender: broadcast::channel(HISTORY_LIMIT).0,
        }
    }
}

impl DashboardHub {
    pub fn insert(&self, snapshot: SessionSnapshot) {
        let mut journal = self.journal.lock().unwrap_or_else(PoisonError::into_inner);
        if journal.sessions.len() >= crate::daemon::MAX_SESSIONS {
            if let Some(oldest) = journal.sessions.keys().next().cloned() {
                journal.sessions.remove(&oldest);
            }
        }
        journal
            .sessions
            .insert(snapshot.session_id.clone(), snapshot);
    }

    pub fn remove(&self, id: &str) {
        self.journal
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .sessions
            .remove(id);
    }

    pub fn publish(&self, id: &str, event: AgentEvent) {
        let mut journal = self.journal.lock().unwrap_or_else(PoisonError::into_inner);
        if let Some(session) = journal.sessions.get_mut(id) {
            match &event {
                AgentEvent::IntentReceived { .. } => session.status = "running".into(),
                AgentEvent::TurnStarted { turn, .. } => session.turns = *turn,
                AgentEvent::TurnCompleted { tokens_used, .. } => session.tokens_used = *tokens_used,
                AgentEvent::ContextMeasured {
                    prompt_tokens,
                    memory_tokens,
                    repo_map_tokens,
                    tool_tokens,
                } => {
                    session.prompt_tokens = *prompt_tokens;
                    session.memory_tokens = *memory_tokens;
                    session.repo_map_tokens = *repo_map_tokens;
                    session.tool_tokens = *tool_tokens;
                }
                AgentEvent::ScratchpadUpdated { plan } => session.scratchpad.clone_from(plan),
                AgentEvent::SessionCompleted { reason } => session.status.clone_from(reason),
                _ => {}
            }
        }
        journal.sequence += 1;
        let frame = EventEnvelope {
            sequence: journal.sequence,
            timestamp_ms: SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map_or(0, |d| d.as_millis() as u64),
            session_id: id.into(),
            event,
        };
        journal.history.push_back(frame.clone());
        if journal.history.len() > HISTORY_LIMIT {
            journal.history.pop_front();
        }
        let _ = self.sender.send(frame);
    }

    pub fn status(&self) -> StatusResponse {
        let journal = self.journal.lock().unwrap_or_else(PoisonError::into_inner);
        StatusResponse {
            protocol_version: 1,
            sessions: journal.sessions.values().cloned().collect(),
            latest_sequence: journal.sequence,
        }
    }

    fn subscribe(&self) -> (Vec<EventEnvelope>, broadcast::Receiver<EventEnvelope>) {
        let journal = self.journal.lock().unwrap_or_else(PoisonError::into_inner);
        (
            journal.history.iter().cloned().collect(),
            self.sender.subscribe(),
        )
    }
}

type ApiResult<T> = Result<Json<T>, (StatusCode, Json<serde_json::Value>)>;

fn api_error(error: Error) -> (StatusCode, Json<serde_json::Value>) {
    let status = if error.code() == "SESSION_NOT_FOUND" {
        StatusCode::NOT_FOUND
    } else {
        StatusCode::CONFLICT
    };
    (
        status,
        Json(serde_json::json!({"code":error.code(), "message":error.to_string()})),
    )
}

async fn status(State(handler): State<Arc<DaemonHandler>>) -> Json<StatusResponse> {
    Json(handler.dashboard_status().await)
}

async fn memory(State(handler): State<Arc<DaemonHandler>>) -> ApiResult<MemoryResponse> {
    handler.dashboard_memory().map(Json).map_err(api_error)
}

async fn plugins(State(handler): State<Arc<DaemonHandler>>) -> Json<Vec<PluginInfo>> {
    Json(handler.dashboard_plugins().await)
}

async fn intervene(
    State(handler): State<Arc<DaemonHandler>>,
    Json(command): Json<Intervention>,
) -> ApiResult<serde_json::Value> {
    handler
        .intervene(command)
        .await
        .map(|()| Json(serde_json::json!({"accepted":true})))
        .map_err(api_error)
}

async fn websocket(State(handler): State<Arc<DaemonHandler>>, ws: WebSocketUpgrade) -> Response {
    // Subscribe under the journal lock before upgrade so no event can fall between replay and live delivery.
    let (history, mut events) = handler.dashboard.subscribe();
    ws.on_upgrade(move |socket| async move {
        let (mut outgoing, mut incoming) = socket.split();
        for event in history {
            let Ok(text) = serde_json::to_string(&event) else {
                return;
            };
            if outgoing.send(Message::Text(text.into())).await.is_err() {
                return;
            }
        }
        loop {
            tokio::select! {
                event = events.recv() => {
                    let Ok(event) = event else {
                        // A slow observer reconnects and receives the bounded replay, never slowing the agent.
                        let _ = outgoing.send(Message::Close(None)).await;
                        return;
                    };
                    let Ok(text) = serde_json::to_string(&event) else { return };
                    if outgoing.send(Message::Text(text.into())).await.is_err() { return; }
                }
                message = incoming.next() => match message {
                    Some(Ok(Message::Close(_))) | None | Some(Err(_)) => return,
                    Some(Ok(Message::Ping(bytes))) => {
                        if outgoing.send(Message::Pong(bytes)).await.is_err() { return; }
                    }
                    _ => {}
                }
            }
        }
    })
}

async fn same_origin(State(authority): State<String>, request: Request, next: Next) -> Response {
    let valid_host = request
        .headers()
        .get(header::HOST)
        .and_then(|v| v.to_str().ok())
        == Some(authority.as_str());
    let origin = format!("http://{authority}");
    let valid_origin = request
        .headers()
        .get(header::ORIGIN)
        .is_none_or(|v| v == origin.as_str());
    let cross_site = request
        .headers()
        .get("sec-fetch-site")
        .is_some_and(|v| v == "cross-site");
    if !valid_host || !valid_origin || cross_site {
        return StatusCode::FORBIDDEN.into_response();
    }
    let mut response = next.run(request).await;
    response.headers_mut().insert(
        header::CACHE_CONTROL,
        axum::http::HeaderValue::from_static("no-store"),
    );
    response.headers_mut().insert(
        header::X_CONTENT_TYPE_OPTIONS,
        axum::http::HeaderValue::from_static("nosniff"),
    );
    response.headers_mut().insert(
        header::CONTENT_SECURITY_POLICY,
        axum::http::HeaderValue::from_static("frame-ancestors 'none'"),
    );
    response
}

pub fn router(
    handler: Arc<DaemonHandler>,
    authority: String,
    assets: std::path::PathBuf,
) -> Router {
    Router::new()
        .route("/api/v1/status", get(status))
        .route("/api/v1/memory", get(memory))
        .route("/api/v1/plugins", get(plugins))
        .route("/api/v1/intervene", post(intervene))
        .route("/ws/events", get(websocket))
        .fallback_service(ServeDir::new(assets).append_index_html_on_directories(true))
        .layer(DefaultBodyLimit::max(16 * 1024))
        .layer(middleware::from_fn_with_state(authority, same_origin))
        .with_state(handler)
}

pub async fn serve(
    handler: Arc<DaemonHandler>,
    mut shutdown: watch::Receiver<bool>,
) -> Result<(), Error> {
    let listener = tokio::net::TcpListener::bind((std::net::Ipv4Addr::LOCALHOST, 4040)).await?;
    let assets = std::env::var_os("LAIN_UI_DIR")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| {
            std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../dashboard/out")
        });
    axum::serve(listener, router(handler, "127.0.0.1:4040".into(), assets))
        .with_graceful_shutdown(async move {
            while !*shutdown.borrow() {
                if shutdown.changed().await.is_err() {
                    break;
                }
            }
        })
        .await?;
    Ok(())
}

