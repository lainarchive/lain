    #[test]
    fn replay_is_bounded_ordered_and_continues_live_without_duplicates() {
        let hub = DashboardHub::default();
        assert!(hub.subscribe().0.is_empty());
        hub.insert(SessionSnapshot {
            session_id: "s".into(),
            ..Default::default()
        });
        for turn in 1..=514 {
            hub.publish(
                "s",
                AgentEvent::TurnStarted {
                    session_id: "s".into(),
                    turn,
                },
            );
        }
        let (history, mut live) = hub.subscribe();
        assert_eq!(history.len(), 512);
        assert_eq!(history.first().unwrap().sequence, 3);
        assert_eq!(history.last().unwrap().sequence, 514);
        assert!(history
            .windows(2)
            .all(|pair| pair.first().unwrap().sequence + 1 == pair.last().unwrap().sequence));
        assert!(matches!(
            live.try_recv(),
            Err(broadcast::error::TryRecvError::Empty)
        ));
        hub.publish(
            "s",
            AgentEvent::ScratchpadUpdated {
                plan: "next".into(),
            },
        );
        assert_eq!(live.try_recv().unwrap().sequence, 515);
        let status = hub.status();
        assert_eq!(status.latest_sequence, 515);
        assert_eq!(status.sessions.first().unwrap().turns, 514);
        assert_eq!(status.sessions.first().unwrap().scratchpad, "next");
        for _ in 0..513 {
            hub.publish("s", AgentEvent::IntentReceived { text: "x".into() });
        }
        assert!(matches!(
            live.try_recv(),
            Err(broadcast::error::TryRecvError::Lagged(_))
        ));
    }

    #[tokio::test]
    async fn websocket_replays_history_then_delivers_live_events() {
        use tokio::io::{AsyncBufReadExt, AsyncReadExt, AsyncWriteExt, BufReader};
        let handler = Arc::new(DaemonHandler::new(
            Arc::new(Mutex::new(
                lain_memory::MemoryStore::open(":memory:").unwrap(),
            )),
            Arc::new(crate::daemon::ConfigFactory::new("missing.json", ".")),
        ));
        handler.dashboard.publish(
            "s",
            AgentEvent::IntentReceived {
                text: "before connection".into(),
            },
        );
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let app = router(
            handler.clone(),
            address.to_string(),
            std::path::PathBuf::from("missing-assets"),
            "test-token".into(),
        );
        let server = tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
        tokio::time::timeout(std::time::Duration::from_secs(5), async {
            let mut socket = tokio::net::TcpStream::connect(address).await.unwrap();
            let request = format!(
                "GET /ws/events HTTP/1.1\r\nHost: {address}\r\nOrigin: http://{address}\r\n\
                 Connection: Upgrade\r\nUpgrade: websocket\r\nSec-WebSocket-Version: 13\r\nSec-WebSocket-Protocol: lain-dashboard, lain-token.test-token\r\n\
                 Sec-WebSocket-Key: dGhlIHNhbXBsZSBub25jZQ==\r\n\r\n"
            );
            socket.write_all(request.as_bytes()).await.unwrap();
            let mut reader = BufReader::new(socket);
            let mut line = String::new();
            reader.read_line(&mut line).await.unwrap();
            assert!(line.starts_with("HTTP/1.1 101"), "{line}");
            loop {
                line.clear();
                reader.read_line(&mut line).await.unwrap();
                if line == "\r\n" {
                    break;
                }
            }
            for (sequence, text) in [(1, "before connection"), (2, "live")] {
                assert_eq!(reader.read_u8().await.unwrap(), 0x81);
                let length = reader.read_u8().await.unwrap();
                assert!(length <= 126, "unexpected frame length: {length}");
                let length = if length == 126 {
                    usize::from(reader.read_u16().await.unwrap())
                } else {
                    usize::from(length)
                };
                let mut payload = vec![0; length];
                reader.read_exact(&mut payload).await.unwrap();
                let frame: serde_json::Value = serde_json::from_slice(&payload).unwrap();
                assert_eq!(frame.get("sequence"), Some(&json!(sequence)));
                assert_eq!(frame.get("session_id"), Some(&json!("s")));
                assert_eq!(
                    frame.get("event"),
                    Some(&json!({"type":"intent_received","text":text}))
                );
                if sequence == 1 {
                    handler.dashboard.publish(
                        "s",
                        AgentEvent::IntentReceived {
                            text: "live".into(),
                        },
                    );
                }
            }
        })
        .await
        .unwrap();
        server.abort();
    }

